#!/usr/bin/env python3
"""
gf.py - Finite field GF(q), q = p^n, with addition and multiplication tables
=============================================================================
Elements are the integers 0..q-1. Integer x stands for the polynomial
sum_i c_i X^i with x = sum_i c_i p^i (0 <= c_i < p), reduced modulo a monic
irreducible polynomial of degree n over GF(p). For prime q this is ordinary
arithmetic modulo q, so the integer labels coincide with residues.

GF(q).add, .mul, .neg are numpy tables, usable with fancy indexing:
    F.add[a, b], F.mul[a, b]  (a, b integer arrays of the same shape)
"""
import itertools
import numpy as np


def factor_prime_power(q):
    for p in range(2, q + 1):
        if q % p == 0:
            n, r = 0, q
            while r % p == 0:
                r //= p; n += 1
            if r != 1:
                raise ValueError(f"{q} is not a prime power")
            return p, n
    raise ValueError(f"{q} is not a prime power")


def _polymulmod(a, b, mod, p):
    """a, b: coefficient lists (low degree first, length n); mod: monic, length n+1."""
    n = len(mod) - 1
    r = [0] * (2 * n - 1)
    for i, ai in enumerate(a):
        if ai:
            for j, bj in enumerate(b):
                r[i + j] = (r[i + j] + ai * bj) % p
    for d in range(2 * n - 2, n - 1, -1):
        c = r[d]
        if c:
            r[d] = 0
            for i in range(n):
                r[d - n + i] = (r[d - n + i] - c * mod[i]) % p
    return r[:n]


def _is_irreducible(mod, p):
    """Brute force: a monic polynomial of degree n <= 3 is irreducible iff it has
    no root; for higher n, check that the multiplicative group of the quotient
    ring has an element of order p^n - 1 (X itself, for a primitive polynomial)."""
    n = len(mod) - 1
    one = [1] + [0] * (n - 1)
    x = [0, 1] + [0] * (n - 2) if n > 1 else [0]
    cur, seen = list(one), set()
    for _ in range(p ** n - 1):
        t = tuple(cur)
        if t in seen:
            return False
        seen.add(t)
        cur = _polymulmod(cur, x, mod, p)
    return cur == one and len(seen) == p ** n - 1   # X primitive -> mod irreducible


class GF:
    def __init__(self, q):
        self.q = q
        self.p, self.n = factor_prime_power(q)
        p, n = self.p, self.n
        if n == 1:
            self.modulus = None
            a = np.arange(q)
            self.add = (a[:, None] + a[None, :]) % q
            self.mul = (a[:, None] * a[None, :]) % q
        else:
            # first monic polynomial (lexicographic in low-degree coefficients)
            # for which X is primitive: the field is then generated by X
            for low in itertools.product(range(p), repeat=n):
                mod = list(low) + [1]
                if low[0] and _is_irreducible(mod, p):
                    break
            self.modulus = mod
            digits = [[(x // p ** i) % p for i in range(n)] for x in range(q)]
            to_int = lambda c: sum(ci * p ** i for i, ci in enumerate(c))
            self.add = np.array([[to_int([(u + v) % p for u, v in zip(digits[a], digits[b])])
                                  for b in range(q)] for a in range(q)])
            self.mul = np.array([[to_int(_polymulmod(digits[a], digits[b], mod, p))
                                  for b in range(q)] for a in range(q)])
        self.neg = np.array([int(np.where(self.add[a] == 0)[0][0]) for a in range(q)])
        self._check()

    def _check(self):
        q, A, M = self.q, self.add, self.mul
        assert all(sorted(A[a]) == list(range(q)) for a in range(q))
        assert all(sorted(M[a]) == list(range(q)) for a in range(1, q))
        assert (A == A.T).all() and (M == M.T).all()
        assert (A[0] == np.arange(q)).all() and (M[1] == np.arange(q)).all()
        # field axioms: all triples (q^3 <= 32768 for the q used here)
        for a, b, c in itertools.product(range(q), repeat=3):
            assert M[a, A[b, c]] == A[M[a, b], M[a, c]]
            assert A[a, A[b, c]] == A[A[a, b], c] and M[a, M[b, c]] == M[M[a, b], c]

    def dot(self, X, P):
        """Matrix product X @ P.T over GF(q): X (r x d), P (c x d) -> (r x c)."""
        out = np.zeros((X.shape[0], P.shape[0]), dtype=np.int64)
        for i in range(X.shape[1]):
            out = self.add[out, self.mul[X[:, i][:, None], P[:, i][None, :]]]
        return out


if __name__ == "__main__":
    for q in (2, 3, 4, 5, 7, 8, 9, 11, 16, 25, 27, 32):
        F = GF(q)
        print(q, "p =", F.p, "n =", F.n, "modulus (low first):", F.modulus)
